const table = ICONS as { name: Record<string, string>; ext: Record<string, string> }

export function fileIconName(path: string, o: { dir?: boolean; open?: boolean } = {}): string {
  if (o.dir) return o.open ? 'folder-open' : 'folder'
  const base = (path.split('/').pop() ?? path).toLowerCase()
  const dot = base.lastIndexOf('.')
  return table.name[base] ?? (dot > 0 ? table.ext[base.slice(dot + 1)] : undefined) ?? 'file'
}
