export function textPixels(text: string): string[] {
  const glyphs = [...text.toLowerCase()].map((c) => GLYPHS[c] ?? GLYPHS[' ']!)
  return [0, 1, 2, 3, 4].map((y) => glyphs.map((g) => g[y]).join('.'))
}
