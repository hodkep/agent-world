const on =
  <A extends unknown[]>(channel: string) =>
  (cb: (...args: A) => void) => {
    const listener = (_: IpcRendererEvent, ...args: unknown[]) => cb(...(args as A))
    ipcRenderer.on(channel, listener)
    return () => void ipcRenderer.removeListener(channel, listener)
  }

